import {test,expect} from '@playwright/test'
test.skip(process.env.EPMS_WORKFLOW_E2E!=='1','Requires isolated workspace fixture')
test('effective periods use explicit basis, retain annual caps and reject overlap',async({page,request})=>{
  test.setTimeout(60000);page.setDefaultTimeout(15000)
  await page.goto('/#/support-budgets?year=2027')
  await page.getByRole('textbox',{name:'전체 지원 예산 (원)',exact:true}).fill('1000000')
  await page.getByRole('textbox',{name:'kg당 지원·기준단가 (원)',exact:true}).fill('100')
  await page.getByRole('checkbox',{name:'이 사업연도의 정산에 지원기준·배정한도 적용',exact:true}).check()
  await page.locator('details.support-periods').getByText(/연도 중 단가 변경·기간별 적용 설정/).click()
  const periods=page.locator('details.support-periods')
  await periods.getByRole('combobox',{name:'지원기준 적용 날짜',exact:true}).selectOption('선적일')
  await periods.getByRole('button',{name:'기간별 단가 추가',exact:true}).click()
  const first=periods.locator('article.report-source').nth(0)
  await first.getByLabel('기간 이름',{exact:true}).fill('상반기 기준');await first.getByLabel('시행 종료일',{exact:true}).fill('2027-06-30');await first.getByLabel('kg당 단가 (원)',{exact:true}).fill('100')
  await periods.getByRole('button',{name:'기간별 단가 추가',exact:true}).click()
  const second=periods.locator('article.report-source').nth(1)
  await second.getByLabel('기간 이름',{exact:true}).fill('하반기 기준');await second.getByLabel('시행 시작일',{exact:true}).fill('2027-07-01');await second.getByLabel('kg당 단가 (원)',{exact:true}).fill('200')
  await page.getByLabel('지원기준·배정 변경 사유',{exact:true}).fill('격리된 2027년 기간별 기준 시연')
  await page.getByRole('button',{name:'지원기준·배정액 저장',exact:true}).click();await expect(page.getByRole('status')).toContainText('저장 완료')
  const headers={'x-epms-token':(await(await request.get('/api/session')).json()).token}
  const data=await(await request.get('/api/org/1/support-budgets/2027',{headers})).json();expect(data.plan.data.date_basis).toBe('선적일');expect(data.plan.data.periods.map((p:{unit_price:string})=>p.unit_price)).toEqual(['100','200'])
  await second.getByLabel('시행 시작일',{exact:true}).fill('2027-06-30');await page.getByLabel('지원기준·배정 변경 사유',{exact:true}).fill('겹침 차단 검증')
  await page.getByRole('button',{name:'지원기준·배정액 저장',exact:true}).click();await expect(page.getByRole('status')).toContainText('겹침')
  await page.screenshot({path:'output/workflow-support-periods.png',fullPage:true})
})
