  test.setTimeout(120000);page.setDefaultTimeout(15000)
  const headers={'x-epms-token':(await(await request.get('/api/session')).json()).token}
  expect((await(await request.get('/api/office',{headers})).json()).item.name).toContain('가상')
  expect((await(await request.get('/api/org/1/support-budgets/2026',{headers})).json()).plan).toBeNull()
  const original=await(await request.get('/api/org/1/settlements/results/1/pdf',{headers})).body(),hash=(b:Buffer)=>createHash('sha256').update(b).digest('hex')
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept())
  await page.goto('/#/support-budgets?year=2026')
  await expect(page.getByRole('status').filter({hasText:'아직 중앙 지원기준'})).toBeVisible()
  await page.getByLabel('전체 지원 예산 (원)',{exact:true}).fill('1000000')
