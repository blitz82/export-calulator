  await page.getByRole('tab',{name:'회원사별 배정한도',exact:true}).click()
  await page.getByRole('textbox',{name:'가상 푸른감귤 영농조합 배정액',exact:true}).fill('50000')
  await page.getByLabel('지원기준·배정 변경 사유',{exact:true}).fill('가상 예산·배정 최초 설정')
  await page.getByRole('button',{name:'지원기준·배정액 저장',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'저장 완료'})).toBeVisible()
  await page.screenshot({path:'output/budget-allocation-screen.png',fullPage:false})
  await page.getByRole('tab',{name:'예산·사용 현황',exact:true}).click()
  await page.getByRole('combobox',{name:'검토할 기존 정산',exact:true}).selectOption('1')
  await page.getByRole('combobox',{name:'예산 반영 결정',exact:true}).selectOption('제외')
  await page.getByLabel('전환 검토 사유',{exact:true}).fill('종전 가정 정산은 새 예산의 사용액으로 자동 인정하지 않음')
