  await expect(page.getByRole('status').filter({hasText:'전환 검토 저장 완료'})).toBeVisible()
  expect((await(await request.get('/api/org/1/support-budgets/2026',{headers})).json()).used).toBe('0')
  await page.goto('/#/sorting?job=1')
  await page.getByRole('button',{name:'지원기준·배정액 확인',exact:true}).click()
  await expect(page.locator('.budget-result')).toContainText('199,000원',{timeout:20000})
  const confirm=page.getByRole('button',{name:'연결 확정·참고 계산 보존',exact:true})
  await expect(confirm).toBeEnabled();await confirm.click();await expect(page.getByRole('button',{name:'결과 PDF 다운로드',exact:true})).toBeVisible()
