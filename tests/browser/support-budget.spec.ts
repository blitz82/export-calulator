  await page.getByRole('textbox',{name:'가상 푸른감귤 영농조합 배정액',exact:true}).fill('300000')
  await page.getByLabel('지원기준·배정 변경 사유',{exact:true}).fill('가상 추가 배정으로 차액 검토')
