  await page.goto('/#/support-budgets?year=2026');await page.getByRole('tab',{name:'예산·사용 현황',exact:true}).click()
  for(const width of [1100,820,500]){await page.setViewportSize({width,height:950});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()}
  expect(errors).toEqual([])
