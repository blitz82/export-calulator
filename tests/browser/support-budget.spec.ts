  await page.goto('/#/sorting?job=1');await page.getByRole('button',{name:'지원기준·배정액 확인',exact:true}).click()
  await expect(page.locator('.budget-result')).toContainText('199,000원',{timeout:20000})
  await expect(confirm).toBeEnabled();await confirm.click();await expect(page.getByRole('button',{name:'결과 PDF 다운로드',exact:true})).toBeVisible()
