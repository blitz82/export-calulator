import {test,expect} from '@playwright/test'
import {readFileSync} from 'node:fs'
test.skip(process.env.EPMS_REQUIREMENTS_E2E!=='1','Requires a dedicated empty requirements test DB')
test('list facilities, optional end date, manual PDF entry, missing fields and formatted weight',async({page,request})=>{
 const session=await(await request.get('/api/session')).json(),headers={'x-epms-token':session.token}
 const organizations=await(await request.get('/api/organizations',{headers})).json()
 expect(organizations.length).toBeLessThanOrEqual(1)
 if(organizations.length)expect(organizations[0].name).toBe('사과')
 const org=organizations[0]??await(await request.post('/api/organizations?name=사과',{headers})).json()
 const stamp=Date.now().toString()
 const root=`/api/org/${org.id}`,path=root+'/settlements'
 const existingMembers=await(await request.get(root+'/data/members',{headers})).json()
 const member=existingMembers.length?[{row:existingMembers[0]}]:await(await request.post(root+'/data/members',{headers,data:[{values:{name:'가상 생산조합',number:'1234567815',kind:'생산자',approved:'2024-01-01'}}]})).json()
 expect(member[0].row).toBeTruthy()
 const doc=await(await request.post(path+'/documents/upload?name=manual.pdf&kind=선별일지',{headers,data:readFileSync('build/manual-synthetic.pdf')})).json()
 await page.goto('/#/facilities')
 await expect(page.getByRole('heading',{name:'공동선별장 명부',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'시설 저장',exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'선별장 신규 등록'}).click()
 await page.locator('input[name="name"]').fill('가상 선별장')
 await page.locator('input[name="designation"]').fill('가상지정'+stamp)
 await page.locator('input[name="valid_from"]').fill('2025-01-01')
 await page.locator('select[name="member_number"]').selectOption(member[0].row.number)
 await page.locator('select[name="evidence_id"]').selectOption(String(doc.id))
 await page.getByRole('button',{name:'시설 저장',exact:true}).click()
 await expect(page.getByRole('cell',{name:'가상 선별장',exact:true}).first()).toBeVisible()
 const allFacilities=await(await request.get(root+'/sorting/facilities',{headers})).json()
 const facilities=allFacilities.filter((f:{data:{designation:string}})=>f.data.designation==='가상지정'+stamp)
 expect(facilities[0].data.valid_to).toBeNull()
 const receipt=await(await request.post(root+'/sorting-receipts',{headers,data:{request_key:'manual-test-receipt'+stamp,facility_id:facilities[0].id,title:'가상 수동 자료',period_type:'일별',start:'2026-07-01',end:'2026-07-01',received:'2026-07-02',documents:[{file:doc.id,page:1}]}})).json()
 await page.goto('/#/sorting-records?receipt='+receipt.id)
 await page.getByRole('button',{name:'2 내용 입력하기',exact:true}).click()
 await page.getByRole('button',{name:'선별기록 추가',exact:true}).click()
 await page.getByRole('button',{name:'PDF 확인·기록 저장',exact:true}).click()
 await expect(page.getByText('수출용 선별량을 입력해 주세요. 미확인과 0은 구분됩니다.',{exact:true}).first()).toBeVisible()
 await page.getByLabel('1행 생산자회원사',{exact:true}).selectOption(String(member[0].row.id))
 const weight=page.getByLabel('1행 수출용 물량',{exact:true})
 await weight.fill('12345.6700');await expect(weight).toHaveValue('12,345.6700')
 await weight.fill('1234567');await expect(weight).toHaveValue('1,234,567')
 await weight.evaluate((input:HTMLInputElement)=>input.setSelectionRange(2,2));await weight.pressSequentially('9');await expect(weight).toHaveValue('19,234,567')
 await weight.press('Backspace');await expect(weight).toHaveValue('1,234,567')
 await weight.fill('');await expect(weight).toHaveValue('');await weight.fill('0');await expect(weight).toHaveValue('0')
 await weight.fill('9,007.123456');await expect(weight).toHaveValue('9,007.123456')
 await page.route('**/api/org/*/settlements/sources',route=>route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({detail:'시험 서버 검증 오류: 입력을 유지하세요.'})}),{times:1})
 await page.getByRole('button',{name:'PDF 확인·기록 저장',exact:true}).click()
 await expect(page.getByRole('alert').filter({hasText:'시험 서버 검증 오류'})).toBeVisible()
 await expect(weight).toHaveValue('9,007.123456')
 await page.getByRole('button',{name:'PDF 확인·기록 저장',exact:true}).click()
 await expect(page.getByRole('status').filter({hasText:'행 저장 완료'})).toBeVisible()
 const allCatalog=await(await request.get(path+'/catalog?records_only=true',{headers})).json()
 const catalog={batches:allCatalog.batches.filter((b:{facility:number})=>b.facility===facilities[0].id)}
 expect(catalog.batches[0].quantity).toBe('9007.123456');expect(catalog.batches[0].ready).toBe(true)
 expect(catalog.batches[0].data.field_evidence).toEqual({})
 await expect(page.getByText('수정 이유를 입력해 주세요.',{exact:true})).toHaveCount(0)
 await page.screenshot({path:'output/manual-intake-verified.png',fullPage:false})
})



